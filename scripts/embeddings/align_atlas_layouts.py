"""Turn the Atlas's twelve layouts onto the one the map opens with (issue #310).

The Atlas draws three data sets (`atlas.json`, the 0.6B; `atlas-qwen3-4b.json`;
`atlas-bm25.json`) at four neighbourhood sizes each. Every layout is an independent
UMAP fit, and UMAP fixes neither orientation, handedness nor scale, so two layouts
that agree on who is near whom still differ by an arbitrary rotation or reflection:
switching from one to another turns the whole map and hides the change that matters,
which instruments moved *relative to the others*.

This script is a step over the exported JSON files (the work directories are on the
cluster, and a committed derived file is regenerated by a person, issue #115), run
after the three exports of `export_atlas_data.py`:

    uv run --group viz python scripts/embeddings/align_atlas_layouts.py \\
        --reference website/pages/atlas/atlas-qwen3-4b.json --layout 16 \\
        website/pages/atlas/atlas.json website/pages/atlas/atlas-qwen3-4b.json \\
        website/pages/atlas/atlas-bm25.json

(the defaults are exactly those three files, that reference and layout 16).
`--check` runs the alignment and exits 1 if any coordinate would change, writing
nothing; `--force` re-aligns a file whose `meta.alignment` names another reference.

Design points:

* **Wasserstein Procrustes with a free plan** (Grave, Joulin and Berthet, AISTATS
  2019). The transform is orthogonal (rotation or reflection) with one uniform scale
  and a translation, the one that minimises the 2-Wasserstein cost between the
  transformed layout and the reference, the transport plan being *free* instead of
  fixed to "instrument `i` is instrument `i`". The global turn is then estimated from
  the shape of the two clouds, so the instruments that genuinely changed
  neighbourhood do not drag it towards themselves, and those are the ones whose
  movement remains. It alternates the closed-form Procrustes step under the current
  plan (SVD of the plan-weighted cross-covariance) and the exact earth mover's plan
  (`ot.emd`) under the current transform; the objective never increases.
* **Exact EMD, uniform masses, squared Euclidean cost**: 2,670 points solve in
  seconds, every instrument is one point to the reader whatever its circle, and
  Sinkhorn would add a regularisation parameter with nothing to buy. POT's default
  `numItermax` (100,000) stops the network simplex before optimality on this size, so
  `NUM_ITER_MAX` is higher and a plan that POT reports as not solved is an error.
* **One reference for all twelve layouts**, the 4B at 16 (the view the map opens on),
  so every switch is a single comparison and not two transforms composed.
* **One common frame**: after alignment one min-max per axis over all twelve layouts
  (the reference included) puts every coordinate in `[0, 1]`, so the page's fixed
  scales hold with no clipping. A layout no longer fills the square on its own.
* **`meta.alignment` in every file**, the reference's own (the identity) included, at
  the same key position (after `umap`): `method`, `reference` (`file`, `model`,
  `n_neighbors`), `pot_version`, `frame` and `layouts`, one record per neighbourhood
  size of that file. Displacements and costs are in the reference's own unit frame,
  before the common frame; `displacement_framed` is what the reader sees after it.
* **Idempotent.** When every file already carries `meta.alignment` for this reference
  the run does nothing (`--force` aligns again): the common frame is a per-axis
  min-max, which is not a similarity, so aligning an aligned layout a second time
  would not return the identity but drift by a fraction of a percent in scale (measured:
  0.3 to 0.7 %), and it would overwrite the first run's record. A file regenerated by
  the exporter has no `meta.alignment`, so the run then aligns all of them again.
  A file none of whose coordinates would move by more than one unit of the last
  decimal is not rewritten.
* **Nothing is written unless every file is accepted**: instruments that differ at any
  position (`c`/`k`), layouts that differ, or a reference that is not among the files
  are a `SystemExit` before the first write.
"""

from __future__ import annotations

import argparse
import json
import sys
import time
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))

REPO = Path(__file__).resolve().parents[2]
PAGES = REPO / "website" / "pages" / "atlas"
DEFAULT_FILES = (PAGES / "atlas.json", PAGES / "atlas-qwen3-4b.json", PAGES / "atlas-bm25.json")
DEFAULT_REFERENCE = PAGES / "atlas-qwen3-4b.json"
DEFAULT_LAYOUT = 16
DEFAULT_DECIMALS = 4          # the exporter's DEFAULT_DECIMALS
#: Network-simplex iterations allowed to `ot.emd`; its default (100,000) stops before
#: optimality on 2,670 points and warns.
NUM_ITER_MAX = 20_000_000
METHOD = "wasserstein-procrustes"
#: Tolerance on the objective's monotonicity (the issue's 1e-9).
OBJECTIVE_TOLERANCE = 1e-9
#: Where `meta.alignment` goes: right after this key.
AFTER_KEY = "umap"
#: The instrument fields that must agree position by position across the files.
INSTRUMENT_KEYS = ("c", "k")


def procrustes(target, source, plan):
    """The orthogonal transform `(s, R, t)` minimising
    `sum(plan[i, j] * |s * source[i] @ R + t - target[j]|**2)`.

    `s` is a uniform scale, `R` a 2x2 orthogonal matrix (`det` +1 or -1, a reflection
    is allowed) and `t` a translation. Closed form: SVD of the plan-weighted
    cross-covariance after plan-weighted centring. With `plan = I / n` this is
    ordinary Procrustes under the known correspondence.
    """
    target, source, plan = (np.asarray(a, dtype=np.float64) for a in (target, source, plan))
    mass = plan.sum()
    a, b = plan.sum(axis=1), plan.sum(axis=0)
    mean_source = a @ source / mass
    mean_target = b @ target / mass
    centred_source, centred_target = source - mean_source, target - mean_target
    cross = centred_source.T @ plan @ centred_target
    u, singular, vt = np.linalg.svd(cross)
    rotation = u @ vt
    spread = float(a @ (centred_source ** 2).sum(axis=1))
    scale = float(singular.sum() / spread) if spread > 0 else 1.0
    translation = mean_target - scale * mean_source @ rotation
    return scale, rotation, translation


def apply(source, transform):
    """`s * source @ R + t`."""
    scale, rotation, translation = transform
    return scale * np.asarray(source, dtype=np.float64) @ rotation + translation


def transport_plan(target, moved):
    """The exact earth mover's plan from `moved` to `target` (uniform masses, squared
    Euclidean cost) and its cost, `(plan, cost)`. A solve that POT does not report as
    optimal is a `RuntimeError`."""
    import ot

    n = len(moved)
    mass = np.full(n, 1.0 / n)
    cost = ot.dist(np.asarray(moved), np.asarray(target))
    plan, log = ot.emd(mass, mass, cost, numItermax=NUM_ITER_MAX, log=True)
    if log.get("warning"):
        raise RuntimeError(f"ot.emd did not reach optimality: {log['warning']}")
    return plan, float((plan * cost).sum())


def displacement(target, moved) -> float:
    """The mean Euclidean distance between instrument `i` in both, the known
    correspondence."""
    return float(np.linalg.norm(np.asarray(moved) - np.asarray(target), axis=1).mean())


def objective(target, source, transform, plan) -> float:
    moved = apply(source, transform)
    return float((plan * ((moved[:, None, :] - np.asarray(target)[None, :, :]) ** 2).sum(-1)).sum())


def align(target, source, *, max_iterations: int = 20):
    """Align `source` onto `target` by Wasserstein Procrustes; `(aligned, record)`.

    Starts from the identity plan and alternates `procrustes` and `transport_plan`
    until the plan stops changing or `max_iterations`. The objective (the plan-weighted
    squared distance) never increases; it is asserted to within `OBJECTIVE_TOLERANCE`.
    """
    target, source = np.asarray(target, dtype=np.float64), np.asarray(source, dtype=np.float64)
    n = len(target)
    if source.shape != target.shape or target.shape[1] != 2:
        raise ValueError(f"layouts of shape {source.shape} and {target.shape}: need n x 2 twice")
    identity = np.eye(n) / n
    plain = procrustes(target, source, identity)
    _, cost_before = transport_plan(target, source)
    plan, transform, history = identity, (1.0, np.eye(2), np.zeros(2)), []
    previous = objective(target, source, transform, identity)
    iterations = 0
    for iterations in range(1, max_iterations + 1):
        transform = procrustes(target, source, plan)
        after_transform = objective(target, source, transform, plan)
        assert after_transform <= previous + OBJECTIVE_TOLERANCE, \
            f"the Procrustes step raised the objective: {previous} -> {after_transform}"
        new_plan, _ = transport_plan(target, apply(source, transform))
        after_plan = objective(target, source, transform, new_plan)
        assert after_plan <= after_transform + OBJECTIVE_TOLERANCE, \
            f"the transport step raised the objective: {after_transform} -> {after_plan}"
        history.append(after_plan)
        stalled = np.abs(new_plan - plan).max() <= 1e-12 or previous - after_plan <= 1e-12
        plan, previous = new_plan, after_plan
        if stalled:
            break
    aligned = apply(source, transform)
    scale, rotation, translation = transform
    _, cost_after = transport_plan(target, aligned)
    record = {
        "iterations": iterations,
        "scale": scale,
        "rotation": rotation.tolist(),
        "reflection": bool(np.linalg.det(rotation) < 0),
        "translation": translation.tolist(),
        "cost_before": cost_before,
        "cost_after": cost_after,
        "displacement_raw": displacement(target, source),
        "displacement_procrustes": displacement(target, apply(source, plain)),
        "displacement_aligned": displacement(target, aligned),
        "diagonal_mass": float(np.trace(plan)),
        "objective": history,
    }
    return aligned, record


def reference_record(target) -> dict:
    """The reference layout against itself: the identity, with nothing to estimate."""
    return {"iterations": 0, "scale": 1.0, "rotation": np.eye(2).tolist(), "reflection": False,
            "translation": [0.0, 0.0], "cost_before": 0.0, "cost_after": 0.0,
            "displacement_raw": 0.0, "displacement_procrustes": 0.0,
            "displacement_aligned": 0.0, "diagonal_mass": 1.0, "objective": []}


def common_frame(layouts):
    """The one min-max per axis over every layout in `layouts`; `{"x": [lo, hi],
    "y": [lo, hi]}`. Applying it to each puts all of them in `[0, 1]`, touching both
    ends on each axis."""
    stacked = np.concatenate([np.asarray(layout, dtype=np.float64) for layout in layouts])
    lows, highs = stacked.min(axis=0), stacked.max(axis=0)
    return {"x": [float(lows[0]), float(highs[0])], "y": [float(lows[1]), float(highs[1])]}


def apply_frame(layout, frame):
    layout = np.asarray(layout, dtype=np.float64)
    lows = np.array([frame["x"][0], frame["y"][0]])
    spans = np.array([frame["x"][1] - frame["x"][0], frame["y"][1] - frame["y"][0]])
    return (layout - lows) / spans


# -- files ------------------------------------------------------------------ #

def _load(path: Path) -> dict:
    return json.loads(Path(path).read_text(encoding="utf-8"))


def _check_files(paths, datas, reference, layout) -> None:
    """Every refusal, before anything is computed or written."""
    if reference not in paths:
        raise SystemExit(f"the reference {reference} is not among the files to align: "
                         f"{', '.join(map(str, paths))}")
    first, first_path = datas[0], paths[0]
    for path, data in zip(paths, datas):
        for key in ("instruments", "projections", "meta"):
            if key not in data:
                raise SystemExit(f"{path} has no `{key}`: it is not an Atlas data file")
        for position, (mine, theirs) in enumerate(zip(data["instruments"], first["instruments"])):
            for key in INSTRUMENT_KEYS:
                if mine[key] != theirs[key]:
                    raise SystemExit(
                        f"instrument {position} differs between {path} and {first_path}: "
                        f"`{key}` is {mine[key]!r} here, {theirs[key]!r} there -- the files do "
                        "not list the same instruments in the same positions")
        if len(data["instruments"]) != len(first["instruments"]):
            raise SystemExit(
                f"{len(data['instruments'])} instruments in {path}, {len(first['instruments'])} in "
                f"{first_path}: they differ from position "
                f"{min(len(data['instruments']), len(first['instruments']))} on")
        if list(data["projections"]) != list(first["projections"]):
            raise SystemExit(
                f"{path} has the layouts {list(data['projections'])}, {first_path} has "
                f"{list(first['projections'])}: every file must hold the same neighbourhood sizes")
        for key, points in data["projections"].items():
            if len(points) != len(data["instruments"]):
                raise SystemExit(f"{path}: layout {key} has {len(points)} points for "
                                 f"{len(data['instruments'])} instruments")
    if str(layout) not in datas[paths.index(reference)]["projections"]:
        raise SystemExit(f"{reference} has no layout {layout!r}: it has "
                         f"{list(datas[paths.index(reference)]['projections'])}")


def _reference_of(path: Path, data: dict, layout: int) -> dict:
    return {"file": Path(path).name, "model": data["meta"].get("model"), "n_neighbors": int(layout)}


def _with_alignment(meta: dict, alignment: dict) -> dict:
    """`meta` with `alignment` right after `AFTER_KEY` (or last when it has none)."""
    rest = {key: value for key, value in meta.items() if key != "alignment"}
    out = {}
    placed = False
    for key, value in rest.items():
        out[key] = value
        if key == AFTER_KEY:
            out["alignment"] = alignment
            placed = True
    if not placed:
        out["alignment"] = alignment
    return out


def _rounded(value, places=8):
    if isinstance(value, dict):
        return {key: _rounded(v, places) for key, v in value.items()}
    if isinstance(value, (list, tuple)):
        return [_rounded(v, places) for v in value]
    if isinstance(value, float):
        return round(value, places)
    return value


def align_files(reference_path, layout, paths, *, decimals: int = DEFAULT_DECIMALS,
                force: bool = False, check: bool = False, max_iterations: int = 20,
                log=print) -> dict:
    """Align every layout of every file in `paths` onto `reference_path`'s `layout`,
    rewrite the files that move, and return `{"changed": [paths], "rows": [...],
    "frame": {...}}`. With `check` nothing is written."""
    import ot

    paths = [Path(p) for p in paths]
    reference_path = Path(reference_path)
    datas = [_load(p) for p in paths]
    _check_files(paths, datas, reference_path, layout)
    reference = _reference_of(reference_path, datas[paths.index(reference_path)], layout)
    for path, data in zip(paths, datas):
        existing = data["meta"].get("alignment")
        if existing and existing.get("reference") != reference and not force:
            raise SystemExit(f"{path} was aligned onto {existing.get('reference')}, not onto "
                             f"{reference}: pass --force to align it again")

    if not force and all((data["meta"].get("alignment") or {}).get("reference") == reference
                         for data in datas):
        log("every file carries meta.alignment for this reference: nothing to align")
        return {"changed": [], "rows": [], "frame": None}

    target = np.asarray(datas[paths.index(reference_path)]["projections"][str(layout)],
                        dtype=np.float64)
    aligned: dict[tuple[int, str], np.ndarray] = {}
    records: dict[tuple[int, str], dict] = {}
    rows = []
    for index, (path, data) in enumerate(zip(paths, datas)):
        for key, points in data["projections"].items():
            started = time.monotonic()
            if path == reference_path and key == str(layout):
                aligned[index, key], records[index, key] = target.copy(), reference_record(target)
            else:
                aligned[index, key], records[index, key] = align(
                    target, points, max_iterations=max_iterations)
            seconds = time.monotonic() - started
            rows.append({"file": path.name, "layout": key, "seconds": seconds,
                         **{k: v for k, v in records[index, key].items() if k != "objective"}})
            log(f"  aligned {path.name} {key} in {seconds:.1f}s")

    frame = common_frame(list(aligned.values()))
    framed_target = apply_frame(target, frame)
    changed = []
    outputs = {}
    for index, (path, data) in enumerate(zip(paths, datas)):
        projections, moved_by = {}, 0.0
        layouts = {}
        for key in data["projections"]:
            framed = apply_frame(aligned[index, key], frame)
            rounded = np.round(framed, decimals)
            projections[key] = rounded.tolist()
            moved_by = max(moved_by, float(np.abs(
                rounded - np.asarray(data["projections"][key], dtype=np.float64)).max()))
            record = dict(records[index, key])
            record.pop("objective")
            record["displacement_framed"] = displacement(framed_target, rounded)
            layouts[key] = record
        for row in rows:
            if row["file"] == path.name and row["layout"] in layouts:
                row["displacement_framed"] = layouts[row["layout"]]["displacement_framed"]
        alignment = {"method": METHOD, "reference": reference, "pot_version": ot.__version__,
                     "frame": _rounded(frame, 6), "layouts": _rounded(layouts)}
        unit = 10.0 ** -decimals
        already = (data["meta"].get("alignment") or {}).get("reference") == reference
        if already and moved_by <= unit * 1.0001:
            continue                      # nothing would move: its first record stays
        changed.append(path)
        outputs[path] = {"meta": _with_alignment(data["meta"], alignment),
                         "instruments": data["instruments"], "projections": projections}
        for key in data:
            if key not in outputs[path]:
                outputs[path][key] = data[key]
    if not check:
        from _atomic import atomic_write_text

        for path, content in outputs.items():
            atomic_write_text(path, json.dumps(content, ensure_ascii=False,
                                               separators=(",", ":")) + "\n")
    return {"changed": changed, "rows": rows, "frame": frame}


def print_table(rows, frame, log=print) -> None:
    log(f"{'file':<24}{'layout':>7}{'iter':>5}{'scale':>8}{'refl':>6}{'raw':>8}{'procr.':>8}"
        f"{'aligned':>9}{'framed':>8}{'cost0':>9}{'cost1':>9}{'diag':>7}{'s':>6}")
    for row in rows:
        log(f"{row['file']:<24}{row['layout']:>7}{row['iterations']:>5}{row['scale']:>8.4f}"
            f"{('yes' if row['reflection'] else 'no'):>6}{row['displacement_raw']:>8.3f}"
            f"{row['displacement_procrustes']:>8.3f}{row['displacement_aligned']:>9.3f}"
            f"{row.get('displacement_framed', float('nan')):>8.3f}{row['cost_before']:>9.4f}"
            f"{row['cost_after']:>9.4f}{row['diagonal_mass']:>7.3f}{row['seconds']:>6.1f}")
    log(f"frame: x in [{frame['x'][0]:.4f}, {frame['x'][1]:.4f}], "
        f"y in [{frame['y'][0]:.4f}, {frame['y'][1]:.4f}]")


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("files", nargs="*", type=Path, default=list(DEFAULT_FILES),
                        help="the Atlas data files to align (default: the three committed ones)")
    parser.add_argument("--reference", type=Path, default=DEFAULT_REFERENCE,
                        help="the file whose layout is the target; it must be among the files")
    parser.add_argument("--layout", type=int, default=DEFAULT_LAYOUT,
                        help="the neighbourhood size of the reference layout")
    parser.add_argument("--decimals", type=int, default=DEFAULT_DECIMALS)
    parser.add_argument("--max-iterations", type=int, default=20)
    parser.add_argument("--force", action="store_true",
                        help="align a file whose meta.alignment names another reference")
    parser.add_argument("--check", action="store_true",
                        help="exit 1 if any coordinate would change; write nothing")
    args = parser.parse_args(argv)
    result = align_files(args.reference, args.layout, args.files, decimals=args.decimals,
                         force=args.force, check=args.check, max_iterations=args.max_iterations)
    if result["rows"]:
        print_table(result["rows"], result["frame"])
    if args.check:
        if result["changed"]:
            print("would change: " + ", ".join(p.name for p in result["changed"]))
            return 1
        print("the files are aligned")
        return 0
    print("rewrote: " + (", ".join(p.name for p in result["changed"]) or "nothing (already aligned)"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
